// Standalone tool — load graph + competition_mission.yaml, validate every
// consecutive pair, auto-insert BFS shortest path for missing edges, write
// mission_expanded.yaml.
//
// Usage:
//   mission_expander <graphml> <mission_yaml> <out_expanded_yaml>
//
// Exit code:
//   0 = no missing edges (mission already legal end-to-end), no file emitted
//   1 = one or more gaps filled (file emitted)
//   2 = one or more pairs UNREACHABLE — file emitted with TODO markers

#include <cstdio>
#include <cstdlib>
#include <fstream>
#include <iostream>
#include <sstream>
#include <string>
#include <vector>

#include <yaml-cpp/yaml.h>

#include "mission_supervisor_cpp/mission_graph.hpp"

using mission_supervisor_cpp::MissionGraph;

namespace {

std::vector<std::string> load_mission_(const std::string & path)
{
  std::vector<std::string> out;
  YAML::Node y = YAML::LoadFile(path);
  if (!y["mission"] || !y["mission"]["path"]) {
    throw std::runtime_error("missing mission.path in " + path);
  }
  for (const auto & n : y["mission"]["path"]) {
    out.push_back(n.as<std::string>());
  }
  return out;
}

void write_expanded_(const std::string & out_path,
                     const std::vector<std::string> & original,
                     const std::vector<std::string> & expanded,
                     const std::vector<std::string> & inserted_segments,
                     const std::vector<std::string> & unreachable_pairs)
{
  std::ofstream f(out_path);
  f << "# =============================================================================\n";
  f << "# competition_mission_expanded.yaml — auto-generated by mission_expander\n";
  f << "# =============================================================================\n";
  f << "# Source: competition_mission.yaml ("
    << original.size() << " nodes)\n";
  f << "# Result: " << expanded.size() << " nodes after auto-fill of "
    << inserted_segments.size() << " missing edges\n";
  if (!unreachable_pairs.empty()) {
    f << "# WARNING: " << unreachable_pairs.size()
      << " pair(s) UNREACHABLE in the graph — see audit comments below\n";
  }
  f << "#\n";
  f << "# Auto-filled segments (each replaces a single A→B pair that had no\n";
  f << "# direct edge with the BFS shortest legal path A→…→B):\n";
  for (const auto & line : inserted_segments) f << "#   " << line << "\n";
  if (!unreachable_pairs.empty()) {
    f << "#\n";
    f << "# UNREACHABLE pairs (NO path exists in graph; race-day operator must\n";
    f << "# hand-edit the underlying graphml or the mission YAML):\n";
    for (const auto & line : unreachable_pairs) f << "#   " << line << "\n";
  }
  f << "# =============================================================================\n\n";

  f << "mission:\n";
  f << "  name:        \"BFMC 2026 — OdyssiX competition mission (auto-expanded)\"\n";
  f << "  version:     \"1.0-expanded\"\n";
  f << "  start_node:  \"" << expanded.front() << "\"\n";
  f << "  goal_node:   \"" << expanded.back()  << "\"\n";
  f << "  total_nodes: " << expanded.size() << "\n";
  f << "  path:\n";
  for (const auto & n : expanded) {
    f << "    - \"" << n << "\"\n";
  }
}

}  // namespace

int main(int argc, char ** argv)
{
  if (argc != 4) {
    std::cerr << "usage: " << argv[0]
              << " <graphml> <mission_yaml> <out_expanded_yaml>\n";
    return 64;
  }
  const std::string graphml_path = argv[1];
  const std::string mission_in   = argv[2];
  const std::string mission_out  = argv[3];

  MissionGraph g;
  std::string err;
  if (!g.load(graphml_path, err)) {
    std::cerr << "FATAL: graph load failed: " << err << "\n";
    return 64;
  }
  std::cerr << "graph loaded — " << g.n_nodes() << " nodes, "
            << g.n_edges() << " edges\n";

  std::vector<std::string> original;
  try { original = load_mission_(mission_in); }
  catch (const std::exception & e) {
    std::cerr << "FATAL: " << e.what() << "\n";
    return 64;
  }
  std::cerr << "mission loaded — " << original.size() << " nodes\n";

  std::vector<std::string> expanded;
  std::vector<std::string> inserted_segments;
  std::vector<std::string> unreachable_pairs;
  expanded.reserve(original.size());

  std::size_t gaps_filled = 0;
  std::size_t hops_inserted = 0;
  for (std::size_t i = 0; i < original.size(); ++i) {
    if (i == 0) { expanded.push_back(original[i]); continue; }
    const std::string & a = original[i - 1];
    const std::string & b = original[i];
    if (g.has_edge(a, b)) {
      expanded.push_back(b);
      continue;
    }
    // Missing edge — fill via BFS shortest path.
    auto path = g.shortest_path(a, b);
    if (path.empty()) {
      std::ostringstream rep;
      rep << "UNREACHABLE: " << a << " → " << b << " (at mission idx " << i << ")";
      unreachable_pairs.push_back(rep.str());
      std::cerr << rep.str() << " — leaving direct jump (operator must resolve)\n";
      expanded.push_back(b);  // keep direct jump as placeholder; flagged in YAML header
      continue;
    }
    // BFS returned [a, x1, x2, ..., b]. We have a already; insert x1..b.
    if (path.size() < 2 || path.front() != a || path.back() != b) {
      std::cerr << "FATAL: BFS returned malformed path from " << a
                << " to " << b << "\n";
      return 64;
    }
    const std::size_t inserted_hops = path.size() - 2;   // intermediate count
    for (std::size_t k = 1; k < path.size(); ++k) {
      expanded.push_back(path[k]);
    }
    ++gaps_filled;
    hops_inserted += inserted_hops;
    std::ostringstream rep;
    rep << a << " → " << b
        << " : inserted " << inserted_hops << " intermediate node(s) [";
    for (std::size_t k = 1; k + 1 < path.size(); ++k) {
      if (k > 1) rep << ", ";
      rep << path[k];
    }
    rep << "]";
    inserted_segments.push_back(rep.str());
    std::cerr << "GAP at mission idx " << i << ": " << rep.str() << "\n";
  }

  std::cerr << "expansion: " << original.size() << " → " << expanded.size()
            << " nodes (" << gaps_filled << " gaps filled, "
            << hops_inserted << " intermediate hops inserted, "
            << unreachable_pairs.size() << " unreachable)\n";

  write_expanded_(mission_out, original, expanded,
                  inserted_segments, unreachable_pairs);
  std::cerr << "wrote " << mission_out << "\n";

  if (!unreachable_pairs.empty()) return 2;
  if (gaps_filled > 0) return 1;
  return 0;
}
